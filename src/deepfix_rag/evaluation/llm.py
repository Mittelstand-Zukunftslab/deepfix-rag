import litellm
from deepeval.models.base_model import DeepEvalBaseLLM


class ProxyJudgeLLM(DeepEvalBaseLLM):
    def __init__(self, model: str, api_base: str, api_key: str, provider: str = "openai", max_tokens: int = 4096, timeout: int = 90):
        self.model = model
        self.api_base = api_base
        self.api_key = api_key
        self.provider = provider
        self.max_tokens = max_tokens
        self.timeout = timeout

    def load_model(self):
        return self.model

    def generate(self, prompt: str, schema=None) -> str:
        r = litellm.completion(
            model=self.model,
            messages=[{"role": "user", "content": prompt}],
            api_base=self.api_base,
            api_key=self.api_key,
            custom_llm_provider=self.provider,
            timeout=self.timeout,
            max_tokens=self.max_tokens,
        )
        val = r.choices[0].message.content or ""
        val = val.strip()
        import re
        match = re.search(r'\{.*\}', val, re.DOTALL)
        if match:
            val = match.group(0)
        return val

    async def a_generate(self, prompt: str, schema=None) -> str:
        r = await litellm.acompletion(
            model=self.model,
            messages=[{"role": "user", "content": prompt}],
            api_base=self.api_base,
            api_key=self.api_key,
            custom_llm_provider=self.provider,
            timeout=self.timeout,
            max_tokens=self.max_tokens,
        )
        return r.choices[0].message.content or "No response generated by judge."

    def get_model_name(self):
        return self.model
